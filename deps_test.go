// A lockfile replaces its manifest: the manifest's ranges would otherwise sit
// next to the installed versions as unchecked duplicates.
func TestLockfileSupersedesManifest(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	write := func(name, content string) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("package.json", `{"dependencies": {"express": "^4.18.0"}}`)
	write("package-lock.json", `{"lockfileVersion": 3, "packages": {"": {}, "node_modules/express": {"version": "4.18.2"}}}`)
	write("requirements.txt", "requests>=2.0\n")
	write("go.mod", "module x\n\nrequire github.com/a/b v1.2.3\n")

	assertDeps(t, scanDependencies(),
		"npm:express@4.18.2",
		"pypi:requests@>=2.0", // no Python lockfile: the manifest is still read
		"go:github.com/a/b@v1.2.3",
	)
}

